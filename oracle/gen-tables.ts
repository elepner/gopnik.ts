import { decodeCp866 } from '../src/tp/cp866';
/** Extract typed-constant tables from G.EXE's data segment into src/data/tables.ts */
import { img } from './disasm';
const DS = 0x10ae * 16;
const pstr = (off: number) => decodeCp866(img.subarray(DS + off + 1, DS + off + 1 + img[DS + off]));
const bytes = (off: number, n: number) => [...img.subarray(DS + off, DS + off + n)];

const enemyTypes = Array.from({ length: 11 }, (_, i) => pstr(0x2e + i * 256));
const ranks = Array.from({ length: 42 }, (_, i) => pstr(0xb42 + i * 256));
const statWeights = Array.from({ length: 11 }, (_, i) => bytes(0x02 + i * 4, 4));
const prices = bytes(0x0b2e, 0x13);
const src = `// Generated by oracle/gen-tables.ts from the original G.EXE data segment. Do not edit.

/** DS:002E + i*256 — names of character/enemy types (string[255]) */
export const TYPE_NAMES: readonly string[] = ${JSON.stringify(enemyTypes, null, 2)}

/** DS:0B42 + i*256 — rank titles by level (понтовость) */
export const RANK_NAMES: readonly string[] = ${JSON.stringify(ranks, null, 2)}

/** DS:0002 + i*4 — stat distribution weights [str, agi, vit, luck] per type */
export const STAT_WEIGHTS: readonly (readonly [number, number, number, number])[] = ${JSON.stringify(statWeights)}

/** DS:0B2E.. — shop prices (bytes) */
export const PRICE = {
  hotdog: ${prices[0]}, beer: ${prices[1]}, glasses: ${prices[2]}, abibas: ${prices[3]}, boots: ${prices[4]},
  leather: ${prices[5]}, adidas: ${prices[6]}, boots2: ${prices[7]}, leather2: ${prices[8]},
  joint: ${prices[10]}, phone: ${prices[11]}, superJoint: ${prices[12]}, tattoo: ${prices[13]}, knuckles: ${prices[14]},
  club: ${prices[15]}, pistol: ${prices[16]}, bullets: ${prices[17]}, silencer: ${prices[18]},
} as const
`;
await Bun.write(new URL('../src/data/tables.ts', import.meta.url), src);
console.log(enemyTypes, ranks.slice(0, 5), statWeights, prices);

const init = Buffer.from(img.subarray(DS, img.length)).toString('base64');
await Bun.write(
  new URL('../src/data/ds-init.ts', import.meta.url),
  `// Generated by oracle/gen-tables.ts: the initialised part of G.EXE's data segment
// (DS:0000..${(img.length - DS).toString(16)}). Out-of-range table reads of the original land here,
// so the port keeps the whole image in its memory and reads names from it.
export const DS_INIT = Uint8Array.from(atob('${init}'), (c) => c.charCodeAt(0));
`
);
